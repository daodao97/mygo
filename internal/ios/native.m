- (void)textViewDidChange:(UITextView *)textView {
  if (self.syncing)
    return;
  self.sending = YES;
  BOOL composing = textView.markedTextRange != nil;
  NSUInteger caret =
      MIN(NSMaxRange(textView.selectedRange), textView.text.length);
  if (composing && ((MyGoEditor *)textView).fieldID) {
    // UIKit's marked range is provisional; surrounding text is committed.
    // Reconcile both in one Go frame, including incremental candidate commits.
    // The sending/markedTextRange guards prevent echoing into UIKit.
    UITextRange *marked = textView.markedTextRange;
    NSUInteger start = [textView offsetFromPosition:textView.beginningOfDocument toPosition:marked.start];
    NSUInteger end = [textView offsetFromPosition:textView.beginningOfDocument toPosition:marked.end];
    goIOSComposition(self.windowID, (char *)textView.text.UTF8String,
      runes([textView.text substringToIndex:start]),
      runes([textView.text substringToIndex:end]),
      runes([textView.text substringToIndex:caret]));
  } else {
    goIOSText(self.windowID, composing ? 1 : 0, (char *)textView.text.UTF8String,
              0, self.contextLength,
              runes([textView.text substringToIndex:caret]));
  }
  self.sending = NO;
  goIOSInputSync(self.windowID);
}
- (void)commitText {
  if (self.editor.markedTextRange) {
    [self.editor unmarkText];
    [self textViewDidChange:self.editor];
  }
}
- (void)textViewDidChangeSelection:(UITextView *)textView {
  if (self.syncing || self.sending || textView.markedTextRange)
    return;
  // UIKit may report the selection moved by an insertion before it reports
  // the new text. Synchronizing the old Go value here would erase that edit.
  // textViewDidChange will deliver the text and its selection together.
  if (![textView.text isEqual:self.synchronizedText])
    return;
  NSUInteger start = MIN(textView.selectedRange.location, textView.text.length),
             end =
                 MIN(NSMaxRange(textView.selectedRange), textView.text.length);
  self.sending = YES;
  goIOSText(self.windowID, 2, NULL,
            runes([textView.text substringToIndex:start]),
            runes([textView.text substringToIndex:end]), 0);
  self.sending = NO;
  goIOSInputSync(self.windowID);
}
