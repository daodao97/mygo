static void firstPresented(MyGoSurface *s, NSUInteger generation) {
  if (generation != s.presentationGeneration || s.firstPresented) return;
  if (!sceneActive || !s.window) { s.presentationQueued = NO; [s requestFrame]; return; }
  s.firstPresented = YES;
  goIOSPresented(s.windowID);
  [((MyGoController *)hostWindow.rootViewController) dismissMyGoLaunch];
}
