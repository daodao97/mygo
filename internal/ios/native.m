static void openURL(NSURL *url) {
  if (!url) return;
  if (!goReady) {
    if (url.isFileURL) {
      if (!pendingFiles) pendingFiles = [NSMutableArray array];
      [pendingFiles addObject:url];
    } else {
      if (!pendingURLs) pendingURLs = [NSMutableArray array];
      [pendingURLs addObject:url];
    }
    return;
  }
  if (url.isFileURL) {
    BOOL access = [url startAccessingSecurityScopedResource];
    goIOSFile((char *)url.path.UTF8String);
    if (access) [url stopAccessingSecurityScopedResource];
  }
  else goIOSURL((char *)url.absoluteString.UTF8String);
}
