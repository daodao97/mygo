- (CGRect)caretRectForPosition:(UITextPosition *)position {
  NSInteger i = [self offsetFromPosition:self.beginningOfDocument toPosition:position];
  NSDictionary *g = [self geometry:"caret" from:i to:i point:CGPointZero];
  return g ? [self localRect:g[@"Caret"]] :
      ((self.secureTextEntry || !self.fieldID || self.markedTextRange)
        ? [self convertRect:self.goCaret fromView:self.superview] : CGRectZero);
}
- (NSArray<UITextSelectionRect *> *)selectionRectsForRange:(UITextRange *)range {
  NSInteger a = [self offsetFromPosition:self.beginningOfDocument toPosition:range.start];
  NSInteger z = [self offsetFromPosition:self.beginningOfDocument toPosition:range.end];
  NSDictionary *g = [self geometry:"selection" from:a to:z point:CGPointZero];
  if (!g) return @[];
  CGRect first = [self caretRectForPosition:range.start], last = [self caretRectForPosition:range.end];
  NSMutableArray *out = [NSMutableArray array];
  NSArray *rects = [g[@"Rects"] isKindOfClass:NSArray.class] ? g[@"Rects"] : @[];
  for (NSDictionary *r in rects) {
    MyGoSelectionRect *s = [MyGoSelectionRect new];
    s.goRect = [self localRect:r];
    s.direction = [r[@"RTL"] boolValue] ? NSWritingDirectionRightToLeft : NSWritingDirectionLeftToRight;
    s.start = CGRectContainsPoint(CGRectInset(s.goRect, -1, -1), CGPointMake(CGRectGetMinX(first), CGRectGetMidY(first)));
    s.end = CGRectContainsPoint(CGRectInset(s.goRect, -1, -1), CGPointMake(CGRectGetMinX(last), CGRectGetMidY(last)));
    [out addObject:s];
  }
  return out;
}
- (CGRect)firstRectForRange:(UITextRange *)range {
  NSArray<UITextSelectionRect *> *rects = [self selectionRectsForRange:range];
  return rects.count ? rects.firstObject.rect : [self caretRectForPosition:range.start];
}
- (UITextPosition *)closestPositionToPoint:(CGPoint)point {
  NSDictionary *g = [self geometry:"hit" from:0 to:0 point:point];
  if (!g) return self.selectedTextRange.end ?: self.beginningOfDocument;
  return [self positionFromPosition:self.beginningOfDocument offset:units(self.text, [g[@"Index"] intValue])];
}
- (UITextPosition *)closestPositionToPoint:(CGPoint)point withinRange:(UITextRange *)range {
  UITextPosition *p = [self closestPositionToPoint:point];
  if ([self comparePosition:p toPosition:range.start] == NSOrderedAscending) return range.start;
  if ([self comparePosition:p toPosition:range.end] == NSOrderedDescending) return range.end;
  return p;
}
- (UITextRange *)characterRangeAtPoint:(CGPoint)point {
  UITextPosition *p = [self closestPositionToPoint:point];
  return [self.tokenizer rangeEnclosingPosition:p withGranularity:UITextGranularityCharacter inDirection:UITextStorageDirectionForward];
}
- (BOOL)canPerformAction:(SEL)action withSender:(id)sender {
  if (action == @selector(undoManager)) return YES;
  if (action == @selector(mygoHardwareCommand:)) {
    if (self.markedTextRange) return NO;
    if (![sender isKindOfClass:UIKeyCommand.class]) return YES;
    NSString *input = ((UIKeyCommand *)sender).input;
    if ([input isEqual:@"\t"] || [input isEqual:UIKeyInputEscape]) return YES;
    if ([input isEqual:@"v"]) return self.editable && UIPasteboard.generalPasteboard.hasStrings;
    if ([input isEqual:@"z"]) return self.editable;
    if (self.secureTextEntry) return NO;
    if ([input isEqual:@"x"] && !self.editable) return NO;
    return YES;
  }
  if (action == @selector(paste:)) return self.editable && UIPasteboard.generalPasteboard.hasStrings;
  if (action == @selector(cut:) && !self.editable) return NO;
  if (self.secureTextEntry) return NO;
  if (action == @selector(copy:) || action == @selector(cut:))
    return self.selectedRange.length > 0;
  if (action == @selector(select:)) return self.text.length > 0 && self.selectedRange.length == 0;
  if (action == @selector(selectAll:)) return self.text.length > self.selectedRange.length;
  return NO;
}
