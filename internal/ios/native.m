- (void)pressesBegan:(NSSet<UIPress *> *)presses withEvent:(UIPressesEvent *)event {
  NSMutableSet *remaining = [NSMutableSet set];
  if (!self.hardwareKeys) self.hardwareKeys = [NSMutableSet set];
  for (UIPress *press in presses) {
    UIKeyCommand *command = self.markedTextRange ? nil : hardwarePressCommand(press.key, NO);
    if (command) { [self.hardwareKeys addObject:@(press.key.keyCode)]; [self mygoHardwareCommand:command]; }
    else [remaining addObject:press];
  }
  if (remaining.count) [super pressesBegan:remaining withEvent:event];
}
- (void)pressesEnded:(NSSet<UIPress *> *)presses withEvent:(UIPressesEvent *)event {
  NSSet *remaining = remainingHardwarePresses(presses, self.hardwareKeys);
  if (remaining.count) [super pressesEnded:remaining withEvent:event];
}
- (void)pressesCancelled:(NSSet<UIPress *> *)presses withEvent:(UIPressesEvent *)event {
  NSSet *remaining = remainingHardwarePresses(presses, self.hardwareKeys);
  if (remaining.count) [super pressesCancelled:remaining withEvent:event];
}
