      ([other isKindOfClass:UIPinchGestureRecognizer.class] || [other isKindOfClass:UIRotationGestureRecognizer.class])) return YES;
  return [gesture isKindOfClass:UILongPressGestureRecognizer.class] ||
      [other isKindOfClass:UILongPressGestureRecognizer.class];
}
- (void)scrollText:(UIPanGestureRecognizer *)gesture {
  if (gesture.state == UIGestureRecognizerStateBegan) {
    [self commitText];
    if (self.contact) {
      goIOSTouch(self.windowID, self.contactID, 3, self.previous.x, self.previous.y);
      self.contact = nil;
    }
    self.origin = [gesture locationInView:self];
    self.velocity = CGPointZero;
  }
  if (gesture.state == UIGestureRecognizerStateBegan || gesture.state == UIGestureRecognizerStateChanged) {
    CGPoint delta = [gesture translationInView:self];
    goIOSScroll(self.windowID, self.origin.x, self.origin.y, -delta.x, -delta.y);
    [gesture setTranslation:CGPointZero inView:self];
  } else if (gesture.state == UIGestureRecognizerStateEnded) {
    self.velocity = [gesture velocityInView:self];
    [self requestFrame];
  } else if (gesture.state == UIGestureRecognizerStateCancelled) {
    self.velocity = CGPointZero;
  }
}
