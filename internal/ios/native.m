- (NSDictionary *)geometry:(const char *)kind from:(NSInteger)start to:(NSInteger)end point:(CGPoint)point {
  if (!self.fieldID || self.secureTextEntry || self.markedTextRange) return nil;
  start = MAX(0, MIN(start, (NSInteger)self.text.length));
  end = MAX(0, MIN(end, (NSInteger)self.text.length));
  CGPoint p = [self convertPoint:point toView:self.superview];
  char *json = goIOSTextGeometry(self.windowID, self.fieldID, (char *)kind,
      runes([self.text substringToIndex:start]), runes([self.text substringToIndex:end]), p.x, p.y);
  NSData *data = [str(json) dataUsingEncoding:NSUTF8StringEncoding];
  free(json);
  NSDictionary *g = [NSJSONSerialization JSONObjectWithData:data options:0 error:nil];
  return [g[@"Valid"] boolValue] ? g : nil;
}
