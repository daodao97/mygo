static int runes(NSString *s) {
  int n = 0;
  for (NSUInteger i = 0; i < s.length; i++, n++) {
    unichar c = [s characterAtIndex:i];
    if (CFStringIsSurrogateHighCharacter(c) && i + 1 < s.length &&
        CFStringIsSurrogateLowCharacter([s characterAtIndex:i + 1]))
      i++;
  }
  return n;
}
static NSUInteger units(NSString *s, int n) {
  NSUInteger i = 0;
  for (int r = 0; r < n && i < s.length; r++, i++) {
    if (CFStringIsSurrogateHighCharacter([s characterAtIndex:i]) &&
        i + 1 < s.length &&
        CFStringIsSurrogateLowCharacter([s characterAtIndex:i + 1]))
      i++;
  }
  return i;
}

static NSArray<UIKeyCommand *> *hardwareCommands(void) {
  static NSArray<UIKeyCommand *> *commands;
  static dispatch_once_t once;
  dispatch_once(&once, ^{
    NSMutableArray *keys = [NSMutableArray array];
    for (NSString *input in @[@"\t", UIKeyInputEscape, @"a", @"c", @"x", @"v", @"z"]) {
      UIKeyModifierFlags mods = [input isEqual:@"\t"] || [input isEqual:UIKeyInputEscape] ? 0 : UIKeyModifierCommand;
      UIKeyCommand *key = [UIKeyCommand keyCommandWithInput:input modifierFlags:mods action:@selector(mygoHardwareCommand:)];
      key.wantsPriorityOverSystemBehavior = YES;
      [keys addObject:key];
      if ([input isEqual:@"\t"] || [input isEqual:@"z"]) {
        UIKeyCommand *shift = [UIKeyCommand keyCommandWithInput:input modifierFlags:mods|UIKeyModifierShift action:@selector(mygoHardwareCommand:)];
        shift.wantsPriorityOverSystemBehavior = YES;
        [keys addObject:shift];
      }
    }
    commands = keys.copy;
  });
  return commands;
}
static void hardwareCommand(uint64_t window, UIKeyCommand *key) {
  BOOL shift = (key.modifierFlags & UIKeyModifierShift) != 0;
  NSString *command = [key.input isEqual:@"\t"] ? (shift ? @"backtab" : @"tab") :
    [key.input isEqual:UIKeyInputEscape] ? @"escape" :
    [key.input isEqual:@"\r"] ? @"enter" : [key.input isEqual:@" "] ? @"space" :
    [key.input isEqual:@"a"] ? @"selectAll" : [key.input isEqual:@"c"] ? @"copy" :
    [key.input isEqual:@"x"] ? @"cut" : [key.input isEqual:@"v"] ? @"paste" : shift ? @"redo" : @"undo";
  goIOSHardwareCommand(window, (char *)command.UTF8String);
}
static UIKeyCommand *hardwarePressCommand(UIKey *key, BOOL surface) {
  if (!key) return nil;
  NSString *input = key.charactersIgnoringModifiers.lowercaseString;
  if (key.keyCode == UIKeyboardHIDUsageKeyboardTab) input = @"\t";
  if (key.keyCode == UIKeyboardHIDUsageKeyboardEscape) input = UIKeyInputEscape;
  UIKeyModifierFlags mods = key.modifierFlags & (UIKeyModifierShift|UIKeyModifierControl|UIKeyModifierAlternate|UIKeyModifierCommand);
  for (UIKeyCommand *command in hardwareCommands())
    if ([command.input isEqual:input] && command.modifierFlags == mods) return command;
  if (surface && mods == 0 && (key.keyCode == UIKeyboardHIDUsageKeyboardReturnOrEnter || key.keyCode == UIKeyboardHIDUsageKeyboardSpacebar))
    return [UIKeyCommand keyCommandWithInput:key.keyCode == UIKeyboardHIDUsageKeyboardSpacebar ? @" " : @"\r" modifierFlags:0 action:@selector(mygoHardwareCommand:)];
  return nil;
}
static NSSet<UIPress *> *remainingHardwarePresses(NSSet<UIPress *> *presses, NSMutableSet<NSNumber *> *handled) {
  NSMutableSet *remaining = [NSMutableSet set];
  for (UIPress *press in presses) {
    NSNumber *code = @(press.key.keyCode);
    if ([handled containsObject:code]) [handled removeObject:code];
    else [remaining addObject:press];
  }
  return remaining;
}

