- (void)tick:(CADisplayLink *)link {
  double dt =
      self.lastTick > 0 ? MIN(link.timestamp - self.lastTick, 0.05) : 1.0 / 60;
  self.lastTick = link.timestamp;
  if (!self.contact &&
      (fabs(self.velocity.x) > 5 || fabs(self.velocity.y) > 5)) {
    goIOSScroll(self.windowID, self.origin.x, self.origin.y,
                -self.velocity.x * dt, -self.velocity.y * dt);
    double decay = exp(-7 * dt);
    self.velocity =
        CGPointMake(self.velocity.x * decay, self.velocity.y * decay);
  }
  if (self.framePending) {
    self.framePending = NO;
    goIOSFrame(self.windowID);
  }
  if (!self.framePending &&
      (self.contact || hypot(self.velocity.x, self.velocity.y) < 5)) {
    self.displayLink.paused = YES;
    self.lastTick = 0;
  }
}
- (void)touchesBegan:(NSSet<UITouch *> *)touches withEvent:(UIEvent *)event {
  if (self.contact)
    return;
  // Commit before Go moves focus: UIKit's resignation notifications would
  // otherwise deliver a pending composition to the newly focused widget.
  [self commitText];
  self.contact = touches.anyObject;
  self.contactID = ++nextTouchID;
  self.origin = self.previous = [self.contact locationInView:self];
  self.previousTime = self.contact.timestamp;
  self.velocity = CGPointZero;
  self.scrolling = NO;
  goIOSTouch(self.windowID, self.contactID, 0, self.origin.x, self.origin.y);
}
- (void)touchesMoved:(NSSet<UITouch *> *)touches withEvent:(UIEvent *)event {
  if (!self.contact || ![touches containsObject:self.contact])
    return;
  CGPoint p = [self.contact locationInView:self];
  double dt = self.contact.timestamp - self.previousTime;
  if (dt > 0) {
    self.velocity =
        CGPointMake((p.x - self.previous.x) / dt, (p.y - self.previous.y) / dt);
  }
  self.scrolling = goIOSTouch(self.windowID, self.contactID, 1, p.x, p.y);
  self.previous = p;
  self.previousTime = self.contact.timestamp;
}
- (void)touchesEnded:(NSSet<UITouch *> *)touches withEvent:(UIEvent *)event {
  if (!self.contact || ![touches containsObject:self.contact])
    return;
  CGPoint p = [self.contact locationInView:self];
  goIOSTouch(self.windowID, self.contactID, 2, p.x, p.y);
  if (!self.scrolling || self.contact.timestamp - self.previousTime > 0.1)
    self.velocity = CGPointZero;
  self.contact = nil;
  if (self.scrolling)
    [self requestFrame];
}
- (void)touchesCancelled:(NSSet<UITouch *> *)touches
               withEvent:(UIEvent *)event {
  if (!self.contact || ![touches containsObject:self.contact])
    return;
  goIOSTouch(self.windowID, self.contactID, 3, self.previous.x,
             self.previous.y);
  self.contact = nil;
  self.velocity = CGPointZero;
}
