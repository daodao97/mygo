void mygo_ios_pixels(uintptr_t view, const void *pixels, int stride, int w,
                     int h) {
  NSData *data = [NSData dataWithBytes:pixels length:stride * h];
  CGDataProviderRef p =
      CGDataProviderCreateWithCFData((__bridge CFDataRef)data);
  CGColorSpaceRef space = CGColorSpaceCreateWithName(kCGColorSpaceSRGB);
  CGImageRef image = CGImageCreate(w, h, 8, 32, stride, space,
                                   kCGBitmapByteOrder32Little |
                                       kCGImageAlphaPremultipliedFirst,
                                   p, NULL, false, kCGRenderingIntentDefault);
  MyGoSurface *s = (__bridge MyGoSurface *)(void *)view;
  [CATransaction begin];
  [CATransaction setDisableActions:YES];
  NSUInteger generation = s.presentationGeneration;
  if (!s.firstPresented) [CATransaction setCompletionBlock:^{ firstPresented(s, generation); }];
  s.layer.contents = (__bridge id)image;
  [CATransaction commit];
  CGImageRelease(image);
  CGColorSpaceRelease(space);
  CGDataProviderRelease(p);
}
