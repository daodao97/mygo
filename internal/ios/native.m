// Keep presentation delegates alive even though UIKit's delegate properties
// are weak. The token also makes dismissal/completion races idempotent.
@interface MyGoPresentation : NSObject <UIAdaptivePresentationControllerDelegate, UIPopoverPresentationControllerDelegate>
@property(nonatomic) uint64_t token;
@property(nonatomic) NSInteger cancelIndex;
@property(nonatomic, copy) NSDictionary *cancellationResult;
- (BOOL)pending;
- (void)cancel;
@property(nonatomic, strong) UIViewController *controller;
- (void)finish:(NSDictionary *)result error:(NSError *)error;
@end
static NSMutableDictionary<NSNumber *, MyGoPresentation *> *presentations;
@implementation MyGoPresentation
- (BOOL)pending { return presentations[@(self.token)] == self; }
- (void)cancel {
  [self finish:self.cancellationResult ?: @{@"Response": @(self.cancelIndex), @"CheckboxChecked": @NO} error:nil];
}
- (void)finish:(NSDictionary *)result error:(NSError *)error {
  if (!NSThread.isMainThread) {
    dispatch_async(dispatch_get_main_queue(), ^{ [self finish:result error:error]; });
    return;
  }
  if (!presentations[@(self.token)]) return;
  [presentations removeObjectForKey:@(self.token)];
  self.controller = nil;
  NSData *data = [NSJSONSerialization dataWithJSONObject:result ?: @{} options:0 error:nil];
  NSString *json = [[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding];
  goIOSSystemResult(self.token, (char *)json.UTF8String, error ? 2 : 0, (char *)error.localizedDescription.UTF8String);
}
- (void)presentationControllerDidDismiss:(UIPresentationController *)presentationController {
  [self cancel];
}
- (void)popoverPresentationControllerDidDismissPopover:(UIPopoverPresentationController *)popover {
  [self presentationControllerDidDismiss:popover];
}
@end
static UIViewController *systemPresenter(uint64_t token) {
  UIViewController *root = hostWindow.rootViewController;
  if (!root || !root.view.window || hostWindow.windowScene.activationState != UISceneActivationStateForegroundActive) {
    goIOSSystemResult(token, NULL, 2, "mygo: system presentation requires an active Scene");
    return nil;
  }
  if (root.presentedViewController || presentations.count || mygo_ios_auth_pending()) {
    goIOSSystemResult(token, NULL, 2, "mygo: another system presentation is active");
    return nil;
  }
  return root;
}
int mygo_ios_auth_state(void) {
  UIViewController *root = hostWindow.rootViewController;
  if (!root || !root.view.window || !sceneActive) return 1;
  return root.presentedViewController || presentations.count ? 2 : 0;
}
static void cancelPresentations(void) {
  NSArray<MyGoPresentation *> *active = presentations.allValues;
  for (MyGoPresentation *delegate in active) {
    [delegate.controller dismissViewControllerAnimated:NO completion:nil];
    [delegate cancel];
  }
}
static MyGoPresentation *registerPresentation(MyGoPresentation *delegate, uint64_t token, UIViewController *controller, UIViewController *parent) {
  if (!presentations) presentations = [NSMutableDictionary dictionary];
  delegate.token = token;
  delegate.controller = controller;
  presentations[@(token)] = delegate;
  // Asking an action sheet for its popover controller can opt into popover
  // presentation even on a phone, hiding the cancel action. Anchor only iPad.
  UIPopoverPresentationController *popover = parent.traitCollection.userInterfaceIdiom == UIUserInterfaceIdiomPad ? controller.popoverPresentationController : nil;
  if (popover) {
    popover.sourceView = parent.view;
    popover.sourceRect = CGRectMake(CGRectGetMidX(parent.view.bounds), CGRectGetMidY(parent.view.bounds), 1, 1);
    popover.permittedArrowDirections = 0;
    if (![controller isKindOfClass:UIAlertController.class]) popover.delegate = delegate;
  }
  // UIAlertController owns its presentation delegate and asserts if an app
  // replaces it. Its cancel action handles outside-popover dismissal.
  if (![controller isKindOfClass:UIAlertController.class]) controller.presentationController.delegate = delegate;
  return delegate;
}
static MyGoPresentation *trackPresentation(uint64_t token, UIViewController *controller, UIViewController *parent) {
  return registerPresentation([MyGoPresentation new], token, controller, parent);
}
void mygo_ios_message(uint64_t token, const char *json) {
  NSDictionary *o = [NSJSONSerialization JSONObjectWithData:[str(json) dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil];
  if ([o[@"CheckboxLabel"] length]) {
    goIOSSystemResult(token, NULL, 1, NULL);
    return;
  }
  UIViewController *parent = systemPresenter(token);
  if (!parent) return;
  NSString *message = o[@"Message"];
  if ([o[@"Detail"] length]) message = [message stringByAppendingFormat:@"\n\n%@", o[@"Detail"]];
  UIAlertControllerStyle style = [o[@"Style"] isEqual:@"actionSheet"] ? UIAlertControllerStyleActionSheet : UIAlertControllerStyleAlert;
  UIAlertController *alert = [UIAlertController alertControllerWithTitle:o[@"Title"] message:message preferredStyle:style];
  MyGoPresentation *delegate = trackPresentation(token, alert, parent);
  delegate.cancelIndex = [o[@"CancelID"] integerValue];
  NSArray *buttons = o[@"Buttons"], *destructive = o[@"DestructiveButtons"];
  BOOL hasCancel = NO;
  for (NSUInteger i = 0; i < buttons.count; i++) {
    UIAlertActionStyle actionStyle = i == delegate.cancelIndex && (buttons.count > 1 || style == UIAlertControllerStyleActionSheet) ? UIAlertActionStyleCancel : UIAlertActionStyleDefault;
    if ([destructive isKindOfClass:NSArray.class] && [destructive containsObject:@(i)]) actionStyle = UIAlertActionStyleDestructive;
    if (actionStyle == UIAlertActionStyleCancel) hasCancel = YES;
    UIAlertAction *action = [UIAlertAction actionWithTitle:buttons[i] style:actionStyle handler:^(UIAlertAction *selected) {
      [delegate finish:@{@"Response": @(i), @"CheckboxChecked": @NO} error:nil];
    }];
    [alert addAction:action];
    if (style == UIAlertControllerStyleAlert && i == [o[@"DefaultID"] integerValue]) alert.preferredAction = action;
  }
  if (style == UIAlertControllerStyleActionSheet && !hasCancel) {
    [alert addAction:[UIAlertAction actionWithTitle:@"Cancel" style:UIAlertActionStyleCancel handler:^(UIAlertAction *action) {
      [delegate finish:@{@"Response": @(delegate.cancelIndex), @"CheckboxChecked": @NO} error:nil];
    }]];
  }
  [parent presentViewController:alert animated:YES completion:nil];
}
void mygo_ios_share(uint64_t token, const char *json) {
  NSDictionary *o = [NSJSONSerialization JSONObjectWithData:[str(json) dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil];
  UIViewController *parent = systemPresenter(token);
  if (!parent) return;
  NSMutableArray *items = [NSMutableArray array];
  if ([o[@"Text"] length]) [items addObject:o[@"Text"]];
  if ([o[@"URL"] length]) [items addObject:[NSURL URLWithString:o[@"URL"]]];
  NSArray *files = o[@"Files"];
  if ([files isKindOfClass:NSArray.class]) for (NSString *path in files) {
    if (![NSFileManager.defaultManager fileExistsAtPath:path]) {
      goIOSSystemResult(token, NULL, 2, "mygo: shared file no longer exists");
      return;
    }
    [items addObject:[NSURL fileURLWithPath:path]];
  }
  UIActivityViewController *activity = [[UIActivityViewController alloc] initWithActivityItems:items applicationActivities:nil];
  MyGoPresentation *delegate = trackPresentation(token, activity, parent);
  delegate.cancellationResult = @{@"Completed": @NO, @"Activity": @""};
  activity.completionWithItemsHandler = ^(UIActivityType type, BOOL completed, NSArray *returned, NSError *error) {
    [delegate finish:@{@"Completed": @(completed), @"Activity": type ?: @""} error:error];
  };
  [parent presentViewController:activity animated:YES completion:nil];
  activity.presentationController.delegate = delegate;
}

// Provider URLs and NSItemProvider representations are temporary. Copy them
// before completing the native delegate, and never hand security-scoped URLs
// to Go. Disk work stays off UIKit's main thread.
static NSError *fileError(NSString *message) {
  return [NSError errorWithDomain:@"MyGoFiles" code:1 userInfo:@{NSLocalizedDescriptionKey:message}];
}
static NSString *copyImport(NSURL *source, NSString *name, NSError **error) {
  NSFileManager *fm = NSFileManager.defaultManager;
  NSURL *cache = [[fm URLsForDirectory:NSCachesDirectory inDomains:NSUserDomainMask].firstObject URLByAppendingPathComponent:@"MyGoImports" isDirectory:YES];
  if (![fm createDirectoryAtURL:cache withIntermediateDirectories:YES attributes:nil error:error]) return nil;
  NSNumber *regular;
  if (![source getResourceValue:&regular forKey:NSURLIsRegularFileKey error:error]) return nil;
  if (!regular.boolValue) { *error = fileError(@"mygo: importing requires a regular file"); return nil; }
  NSString *filename = name.lastPathComponent;
  if (!filename.length || [filename isEqual:@"."] || [filename isEqual:@".."]) filename = @"file";
  NSURL *target = [cache URLByAppendingPathComponent:[NSString stringWithFormat:@"%@-%@", NSUUID.UUID.UUIDString, filename]];
  if (![fm copyItemAtURL:source toURL:target error:error]) {
    [fm removeItemAtURL:target error:nil];
    return nil;
  }
  return target.path;
}
static void removeImports(NSArray<NSString *> *paths) {
  for (NSString *path in paths) [NSFileManager.defaultManager removeItemAtPath:path error:nil];
}

@interface MyGoFilePresentation : MyGoPresentation <UIDocumentPickerDelegate, PHPickerViewControllerDelegate>
@property(nonatomic) BOOL exporting;
@property(nonatomic) BOOL loading;
@end
@implementation MyGoFilePresentation
- (void)completeImports:(NSArray<NSString *> *)paths error:(NSError *)error {
  NSAssert(NSThread.isMainThread, @"Import results must return on the main thread");
  if (![self pending] || error) {
    dispatch_async(dispatch_get_global_queue(QOS_CLASS_UTILITY, 0), ^{ removeImports(paths); });
    if ([self pending]) [self finish:nil error:error];
    return;
  }
  [self finish:@{@"Paths":paths} error:nil];
}
- (void)documentPickerWasCancelled:(UIDocumentPickerViewController *)controller {
  [self cancel];
}
- (void)documentPicker:(UIDocumentPickerViewController *)controller didPickDocumentsAtURLs:(NSArray<NSURL *> *)urls {
  if (![self pending] || self.loading) return;
  self.loading = YES;
  if (self.exporting) {
    [self finish:@{@"Completed":@((BOOL)(urls.count > 0))} error:nil];
    return;
  }
  // Keep scope valid while coordinating and copying on a worker queue.
  NSMutableArray<NSURL *> *scopes = [NSMutableArray array];
  for (NSURL *url in urls) if ([url startAccessingSecurityScopedResource]) [scopes addObject:url];
  dispatch_async(dispatch_get_global_queue(QOS_CLASS_UTILITY, 0), ^{
    @autoreleasepool {
      NSMutableArray<NSString *> *paths = [NSMutableArray array];
      __block NSError *error;
      for (NSURL *url in urls) {
        NSError *coordinationError;
        NSFileCoordinator *coordinator = [[NSFileCoordinator alloc] initWithFilePresenter:nil];
        [coordinator coordinateReadingItemAtURL:url options:NSFileCoordinatorReadingWithoutChanges error:&coordinationError byAccessor:^(NSURL *readURL) {
          NSString *path = copyImport(readURL, url.lastPathComponent, &error);
          if (path) [paths addObject:path];
        }];
        if (!error) error = coordinationError;
        if (error) break;
      }
      for (NSURL *url in scopes) [url stopAccessingSecurityScopedResource];
      dispatch_async(dispatch_get_main_queue(), ^{ [self completeImports:paths error:error]; });
    }
  });
}
- (void)picker:(PHPickerViewController *)picker didFinishPicking:(NSArray<PHPickerResult *> *)results {
  if (![self pending] || self.loading) return;
  self.loading = YES;
  [picker dismissViewControllerAnimated:YES completion:nil];
  if (!results.count) { [self cancel]; return; }
  dispatch_group_t group = dispatch_group_create();
  NSLock *lock = [NSLock new];
  NSMutableArray *paths = [NSMutableArray array];
  for (NSUInteger i = 0; i < results.count; i++) [paths addObject:NSNull.null];
  __block NSError *batchError;
  [results enumerateObjectsUsingBlock:^(PHPickerResult *result, NSUInteger index, BOOL *stop) {
    NSItemProvider *provider = result.itemProvider;
    NSString *type;
    for (NSString *identifier in provider.registeredTypeIdentifiers) {
      if ([[UTType typeWithIdentifier:identifier] conformsToType:UTTypeImage]) { type = identifier; break; }
    }
    if (!type) { [lock lock]; if (!batchError) batchError = fileError(@"mygo: selected photo has no file representation"); [lock unlock]; return; }
    dispatch_group_enter(group);
    [provider loadFileRepresentationForTypeIdentifier:type completionHandler:^(NSURL *url, NSError *error) {
      @autoreleasepool {
        NSString *path;
        if (url && !error) {
          NSString *name = provider.suggestedName.lastPathComponent;
          if (!name.length) name = url.lastPathComponent;
          NSString *ext = url.pathExtension.length ? url.pathExtension : [UTType typeWithIdentifier:type].preferredFilenameExtension;
          if (ext.length && ![name.pathExtension.lowercaseString isEqual:ext.lowercaseString])
            name = [name.stringByDeletingPathExtension stringByAppendingPathExtension:ext];
          // The system deletes url after this completion handler returns.
          path = copyImport(url, name, &error);
        }
        if (!path && !error) error = fileError(@"mygo: photo provider returned no file");
        [lock lock];
        if (path) paths[index] = path;
        if (error && !batchError) batchError = error;
        [lock unlock];
        dispatch_group_leave(group);
      }
    }];
  }];
  dispatch_group_notify(group, dispatch_get_main_queue(), ^{
    NSMutableArray *copied = [NSMutableArray array];
    for (id path in paths) if ([path isKindOfClass:NSString.class]) [copied addObject:path];
    [self completeImports:copied error:batchError];
  });
}
@end

static void presentFiles(uint64_t token, UIDocumentPickerViewController *picker, UIViewController *parent, BOOL exporting) {
  MyGoFilePresentation *delegate = [MyGoFilePresentation new];
  delegate.exporting = exporting;
  delegate.cancellationResult = exporting ? @{@"Completed":@NO} : @{@"Paths":@[]};
  picker.modalPresentationStyle = UIModalPresentationPageSheet;
  registerPresentation(delegate, token, picker, parent);
  picker.delegate = delegate;
  [parent presentViewController:picker animated:YES completion:nil];
  picker.presentationController.delegate = delegate;
}
void mygo_ios_open_files(uint64_t token, const char *json) {
  NSDictionary *o = [NSJSONSerialization JSONObjectWithData:[str(json) dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil];
  if ([o[@"OpenDirectories"] boolValue]) { goIOSSystemResult(token, NULL, 1, NULL); return; }
  UIViewController *parent = systemPresenter(token);
  if (!parent) return;
  NSMutableArray<UTType *> *types = [NSMutableArray array];
  NSArray *filters = o[@"Filters"];
  BOOL anyType = NO;
  if ([filters isKindOfClass:NSArray.class]) for (NSDictionary *filter in filters) {
    NSArray *extensions = filter[@"Extensions"];
    if (![extensions isKindOfClass:NSArray.class]) continue;
    for (NSString *extension in extensions) {
      if ([extension isEqual:@"*"]) { anyType = YES; break; }
      UTType *type = [UTType typeWithFilenameExtension:extension];
      if (!type) { goIOSSystemResult(token, NULL, 2, "mygo: file filter extension has no iOS content type"); return; }
      if (![types containsObject:type]) [types addObject:type];
    }
    if (anyType) break;
  }
  if (anyType) { [types removeAllObjects]; [types addObject:UTTypeItem]; }
  if (!types.count) [types addObject:UTTypeItem];
  // Borrow scoped access only while making our cache copy. Asking UIKit to
  // import too would leave an additional caller-owned Inbox copy behind.
  UIDocumentPickerViewController *picker = [[UIDocumentPickerViewController alloc] initForOpeningContentTypes:types asCopy:NO];
  picker.allowsMultipleSelection = [o[@"Multiple"] boolValue];
  if ([o[@"Title"] length]) picker.title = o[@"Title"];
  presentFiles(token, picker, parent, NO);
}
void mygo_ios_export_files(uint64_t token, const char *json) {
  NSDictionary *o = [NSJSONSerialization JSONObjectWithData:[str(json) dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil];
  UIViewController *parent = systemPresenter(token);
  if (!parent) return;
  NSMutableArray<NSURL *> *urls = [NSMutableArray array];
  for (NSString *path in o[@"Files"]) {
    BOOL directory;
    if (![NSFileManager.defaultManager fileExistsAtPath:path isDirectory:&directory] || directory) {
      goIOSSystemResult(token, NULL, 2, "mygo: exported file no longer exists"); return;
    }
    [urls addObject:[NSURL fileURLWithPath:path]];
  }
  UIDocumentPickerViewController *picker = [[UIDocumentPickerViewController alloc] initForExportingURLs:urls asCopy:YES];
  if ([o[@"Title"] length]) picker.title = o[@"Title"];
  presentFiles(token, picker, parent, YES);
}
