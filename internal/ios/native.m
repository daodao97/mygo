static UIColor *launchColor(NSString *hex, UIColor *fallback) {
  if (![hex isKindOfClass:NSString.class] || hex.length != 7 || ![hex hasPrefix:@"#"]) return fallback;
  unsigned rgb = (unsigned)strtoul(hex.UTF8String + 1, NULL, 16);
  return [UIColor colorWithRed:((rgb >> 16) & 255) / 255.0 green:((rgb >> 8) & 255) / 255.0 blue:(rgb & 255) / 255.0 alpha:1];
}
static double linearChannel(double c) {
  return c <= 0.04045 ? c / 12.92 : pow((c + 0.055) / 1.055, 2.4);
}
static UIStatusBarStyle statusStyle(UIColor *color, UITraitCollection *traits) {
  CGFloat r, g, b, a, br, bg, bb, ba;
  UIColor *base = [UIColor.systemBackgroundColor resolvedColorWithTraitCollection:traits];
  if (![[color resolvedColorWithTraitCollection:traits] getRed:&r green:&g blue:&b alpha:&a] ||
      ![base getRed:&br green:&bg blue:&bb alpha:&ba]) return UIStatusBarStyleDefault;
  r = r * a + br * (1 - a); g = g * a + bg * (1 - a); b = b * a + bb * (1 - a);
  double luminance = 0.2126 * linearChannel(r) + 0.7152 * linearChannel(g) + 0.0722 * linearChannel(b);
  return luminance < 0.179 ? UIStatusBarStyleLightContent : UIStatusBarStyleDarkContent;
}
