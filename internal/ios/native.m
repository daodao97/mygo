      options:(UISceneConnectionOptions *)options {
  if (![scene isKindOfClass:UIWindowScene.class]) return;
  self.window = [[UIWindow alloc] initWithWindowScene:(UIWindowScene *)scene];
  hostWindow = self.window;
  self.window.overrideUserInterfaceStyle = appearance;
  self.window.rootViewController = [MyGoController new];
  [self.window makeKeyAndVisible];
  for (UIOpenURLContext *context in options.URLContexts) openURL(context.URL);
  for (NSUserActivity *activity in options.userActivities)
    if ([activity.activityType isEqual:NSUserActivityTypeBrowsingWeb]) openURL(activity.webpageURL);
  mygo_ios_notification_response((uintptr_t)(__bridge void *)options.notificationResponse);
  if (!goStarted) {
    goStarted = YES;
    dispatch_async(dispatch_get_global_queue(QOS_CLASS_USER_INITIATED, 0), ^{ MyGoIOSMain(); });
  } else {
    lifecycle(7);
  }
}
- (void)sceneWillResignActive:(UIScene *)scene {
  sceneActive = NO;
  MyGoSurface *s = hostSurface;
  [s commitText];
  [s touchesCancelled:s.contact ? [NSSet setWithObject:s.contact] : [NSSet set] withEvent:nil];
  s.displayLink.paused = YES;
  s.velocity = CGPointZero;
  s.lastTick = 0;
  lifecycle(0);
}
- (void)sceneDidBecomeActive:(UIScene *)scene {
  sceneActive = YES;
  lifecycle(1);
  [hostSurface requestFrame];
}
- (void)sceneDidEnterBackground:(UIScene *)scene {
  sceneActive = NO;
  mygo_ios_auth_cancel_all();
  hostSurface.displayLink.paused = YES;
  // Finish the synchronous checkpoint within an OS-granted background task.
  __block UIBackgroundTaskIdentifier task = UIBackgroundTaskInvalid;
  task = [UIApplication.sharedApplication beginBackgroundTaskWithName:@"MyGo checkpoint" expirationHandler:^{
    if (task != UIBackgroundTaskInvalid) {
      [UIApplication.sharedApplication endBackgroundTask:task];
      task = UIBackgroundTaskInvalid;
    }
  }];
  lifecycle(5);
  if (task != UIBackgroundTaskInvalid) [UIApplication.sharedApplication endBackgroundTask:task];
  task = UIBackgroundTaskInvalid;
}
- (void)sceneWillEnterForeground:(UIScene *)scene { lifecycle(6); }
- (void)sceneDidDisconnect:(UIScene *)scene {
  sceneActive = NO;
  [hostSurface commitText];
  mygo_ios_auth_cancel_all();
  cancelPresentations();
  hostSurface.displayLink.paused = YES;
  [hostSurface.editor resignFirstResponder];
  [hostSurface removeFromSuperview];
  hostSurface.presentationGeneration++;
  hostSurface.firstPresented = NO;
  hostSurface.presentationQueued = NO;
  lifecycle(8);
  hostWindow = nil;
  self.window = nil;
}
- (void)scene:(UIScene *)scene openURLContexts:(NSSet<UIOpenURLContext *> *)contexts {
  for (UIOpenURLContext *context in contexts) openURL(context.URL);
}
- (void)scene:(UIScene *)scene continueUserActivity:(NSUserActivity *)activity {
  if ([activity.activityType isEqual:NSUserActivityTypeBrowsingWeb]) openURL(activity.webpageURL);
}
