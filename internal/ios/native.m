void mygo_ios_access(uintptr_t view, const char *json) {
  MyGoSurface *s = (__bridge MyGoSurface *)(void *)view;
  NSDictionary *t = [NSJSONSerialization
      JSONObjectWithData:[str(json) dataUsingEncoding:NSUTF8StringEncoding]
                 options:0
                   error:nil];
  NSMutableArray *a = [NSMutableArray array];
  s.editor.isAccessibilityElement = NO;
  for (NSDictionary *n in t[@"Nodes"]) {
    unsigned states = [n[@"States"] unsignedIntValue];
    int role = [n[@"Role"] intValue];
    if (states & (1 << 10))
      continue;
    NSString *label = n[@"Label"] ?: @"";
    NSString *value = n[@"Value"] ?: @"";
    if (role == 0 || (!label.length && !value.length))
      continue;
    MyGoAccess *e = [[MyGoAccess alloc] initWithAccessibilityContainer:s];
    e.windowID = s.windowID;
    e.nodeID = strtoull([n[@"ID"] UTF8String], NULL, 10);
    e.actions = [n[@"Actions"] unsignedIntValue];
    e.isAccessibilityElement = YES;
    e.accessibilityLabel = label;
    e.accessibilityValue = value;
    e.accessibilityHint = n[@"Description"];
    e.accessibilityIdentifier = label.length ? label : value;
    UIAccessibilityTraits traits = UIAccessibilityTraitNone;
    if ((e.actions & 1) && role != 3)
      traits |= UIAccessibilityTraitButton;
    if (role == 3)
      traits |= UIAccessibilityTraitLink;
    if (role == 1)
      traits |= UIAccessibilityTraitStaticText;
    if (role == 10)
      traits |= UIAccessibilityTraitImage;
    if (role == 7 || role == 35)
      traits |= UIAccessibilityTraitAdjustable;
    if (role == 43)
      traits |= UIAccessibilityTraitHeader;
    if (states & (1 << 1))
      traits |= UIAccessibilityTraitNotEnabled;
    if (states & ((1 << 2) | (1 << 4)))
      traits |= UIAccessibilityTraitSelected;
    e.accessibilityTraits = traits;
    NSDictionary *b = n[@"Bounds"];
    CGRect bounds =
        CGRectMake([b[@"X"] doubleValue], [b[@"Y"] doubleValue],
                   [b[@"W"] doubleValue], [b[@"H"] doubleValue]);
    bounds = CGRectIntersection(bounds, s.bounds);
    if (CGRectIsEmpty(bounds)) continue;
    e.accessibilityFrameInContainerSpace = bounds;
    // Expose the actual first responder for the focused field. UIKit then
    // provides editable-text and keyboard-focus semantics to VoiceOver
    // and UI automation while Go continues drawing and owning its value.
    if ([n[@"ID"] isEqual:t[@"Focus"]] &&
        (role == 9 || role == 32 || (role == 1 && ((MyGoEditor *)s.editor).fieldID == e.nodeID))) {
      s.editor.isAccessibilityElement = YES;
      s.editor.accessibilityLabel = label;
      s.editor.accessibilityIdentifier = label;
      s.editor.accessibilityHint = n[@"Description"];
      ((MyGoEditor *)s.editor).goAccessibilityFrame =
          [s convertRect:bounds toView:nil];
      [a addObject:s.editor];
      continue;
    }
    [a addObject:e];
  }
  s.goAccessibilityElements = a;
  NSArray *announcements = t[@"Announcements"];
  if ([announcements isKindOfClass:NSArray.class]) {
    for (NSString *announcement in announcements)
      UIAccessibilityPostNotification(UIAccessibilityAnnouncementNotification,
                                      announcement);
  }
}
