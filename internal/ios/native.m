void mygo_ios_input(uintptr_t view, bool active, bool readonly, bool password, bool multiline,
                    const char *text, int start, int end, double x, double y,
                    double w, double h) {
  MyGoSurface *s = (__bridge MyGoSurface *)(void *)view;
  UITextView *e = s.editor;
  BOOL syncing = s.syncing;
  s.syncing = YES;
 MyGoController *controller=(MyGoController *)hostWindow.rootViewController;
 controller.keyboardScroll.scrollEnabled=active && !readonly && [controller.keyboardDismiss isEqual:@"interactive"];
  if (!active) {
    [UIMenuController.sharedMenuController hideMenuFromView:e];
    e.tintColor = UIColor.clearColor;
    ((MyGoEditor *)e).fieldID = 0;
    e.frame = CGRectZero;
    [e resignFirstResponder];
    if (sceneActive && s.window) [s becomeFirstResponder];
    if (@available(iOS 17.0, *)) ((MyGoEditor *)e).selectionDisplay.activated = NO;
    s.syncing = syncing;
    return;
  }
  BOOL changedReadOnly = e.editable==readonly;
 e.editable = !readonly;
 if (readonly && !e.inputView) e.inputView=[UIView new];
 if (!readonly && e.inputView) e.inputView=nil;
  BOOL changedPassword = e.secureTextEntry != password;
  e.secureTextEntry = password;
  ((MyGoEditor *)e).multiline = multiline;
  ((MyGoEditor *)e).goCaret = CGRectMake(x, y, w, h);
  e.tintColor = ((MyGoEditor *)e).fieldID && !password && !e.markedTextRange && mygo_ios_native_selection()
      ? UIColor.systemBlueColor : UIColor.clearColor;
  if (!s.sending && !e.markedTextRange) {
    NSString *t = str(text);
    if (![e.text isEqual:t])
      e.text = t;
    s.synchronizedText = t;
    NSUInteger a = units(t, start), z = units(t, end);
    e.selectedRange = NSMakeRange(a, z - a);
    s.contextLength = runes(t);
  }
  s.contextLength = runes(str(text));
  // Go fields share one UITextView. Apply security and input-view changes
  // after all traits/text are set, so Tab into a password cannot keep the
  // previous field's composing keyboard session.
  if ((changedReadOnly || changedPassword) && e.isFirstResponder) [e reloadInputViews];
  if (!e.isFirstResponder && !interactiveKeyboardTracking())
    [e becomeFirstResponder];
  if (@available(iOS 17.0, *)) {
    UITextSelectionDisplayInteraction *selection = ((MyGoEditor *)e).selectionDisplay;
    selection.activated = ((MyGoEditor *)e).fieldID && !password && !e.markedTextRange;
    [selection setNeedsSelectionUpdate];
    [selection layoutManagedSubviews];
    // These views were created while the keyboard proxy's tint was clear.
    // UITextView updates its own internal display, so update our display too.
    selection.cursorView.tintColor = e.tintColor;
    selection.cursorView.blinking = YES;
    selection.highlightView.tintColor = e.tintColor;
    selection.highlightView.alpha = 0.2;
    for (UIView *handle in selection.handleViews) handle.tintColor = e.tintColor;
  }
  s.syncing = syncing;
}
